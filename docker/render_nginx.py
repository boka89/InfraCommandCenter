"""Render /tmp/nginx/nginx.conf from ICC_* environment variables (called by entrypoint.sh)."""
import os
import re
from urllib.parse import urlparse

E = os.environ.get


def resolver():
    if E("ICC_RESOLVER"):
        return E("ICC_RESOLVER")
    try:
        for line in open("/etc/resolv.conf"):
            p = line.split()
            if len(p) >= 2 and p[0] == "nameserver":
                return f"[{p[1]}]" if ":" in p[1] else p[1]
    except OSError:
        pass
    return "127.0.0.11"


def origin(url):
    u = urlparse(url or "")
    return f"{u.scheme}://{u.netloc}" if u.scheme and u.netloc else ""


def upstream(url):
    """-> (base url without trailing slash, host header) for a proxy_pass with variables"""
    u = urlparse(url)
    if u.scheme not in ("http", "https") or not u.netloc:
        raise SystemExit(f"invalid upstream URL: {url!r}")
    return url.rstrip("/"), u.netloc


metrics = E("ICC_METRICS_URL", "").strip()
docs = E("ICC_DOCS_URL", "").strip()
frames = " ".join(x for x in ["'self'", origin(E("ICC_GRAFANA_URL", ""))] + E("ICC_FRAME_SRC", "").split() if x)
def num(name, default):
    """port from env; ignores Docker/Kubernetes link variables such as ICC_PORT=tcp://10.0.0.1:80"""
    v = E(name, "")
    return int(v) if v.isdigit() else default


port = num("ICC_PORT", 8080)
sd_port = num("ICC_SD_PORT", 8081)
api = f"127.0.0.1:{num('ICC_API_PORT', 8090)}"

metrics_block = '    location /api/vm/ { default_type application/json; return 503 \'{"error":"no metrics backend configured (ICC_METRICS_URL)"}\'; }\n'
if metrics:
    base, host = upstream(metrics)
    auth = E("ICC_METRICS_AUTH_HEADER", "")
    metrics_block = f"""    # Prometheus-compatible metrics backend: read-only query API only
    location ~ ^/api/vm/(api/v1/(query|query_range|series|labels|label/[A-Za-z0-9_]+/values))$ {{
        limit_except GET {{ deny all; }}
        set $vm "{base}";
        proxy_pass $vm/$1$is_args$args;
        proxy_set_header Host "{host}";
        proxy_set_header Cookie "";
        proxy_set_header Authorization "{auth}";
        proxy_ssl_server_name on;
        proxy_read_timeout 30s;
    }}
    location /api/vm/ {{ return 403; }}
"""
docs_block = "    location /api/docs/ { return 404; }\n"
if docs:
    base, host = upstream(docs)
    docs_block = f"""    # MkDocs search index of the organisation's documentation (read-only)
    location = /api/docs/search/search_index.json {{
        limit_except GET {{ deny all; }}
        set $docs "{base}";
        proxy_pass $docs/search/search_index.json;
        proxy_set_header Host "{host}";
        proxy_set_header Cookie "";
        proxy_ssl_server_name on;
    }}
    location /api/docs/ {{ return 404; }}
"""

conf = f"""# generated by /app/docker/render_nginx.py — do not edit
worker_processes 1;
pid /tmp/nginx/nginx.pid;
error_log /dev/stderr warn;
events {{ worker_connections 512; }}
http {{
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    access_log /dev/stdout;
    client_body_temp_path /tmp/nginx/body;
    proxy_temp_path /tmp/nginx/proxy;
    fastcgi_temp_path /tmp/nginx/fastcgi;
    uwsgi_temp_path /tmp/nginx/uwsgi;
    scgi_temp_path /tmp/nginx/scgi;
    sendfile on;
    server_tokens off;
    gzip on;
    gzip_types text/css application/javascript application/json image/svg+xml;
    resolver {resolver()} valid=30s ipv6=off;

    server {{
        listen {port};
        server_name _;
        root /app/web;

        add_header X-Content-Type-Options nosniff always;
        add_header Referrer-Policy same-origin always;
        add_header X-Frame-Options SAMEORIGIN always;
        add_header Content-Security-Policy "default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self'; frame-src {frames}; connect-src 'self'; frame-ancestors 'self'" always;

        # Everything needs a session (the API checks the icc_s cookie), except the login page and
        # its assets, fonts, the health check and /papi/ (which authenticates itself).
        auth_request /_auth;
        location = /_auth {{
            internal;
            proxy_pass http://{api}/papi/auth;
            proxy_pass_request_body off;
            proxy_set_header Content-Length "";
            proxy_set_header Cookie $http_cookie;
        }}

        location = /healthz {{ auth_request off; access_log off; default_type text/plain; return 200 "ok\\n"; }}
        location ~ ^/(login\\.html|login\\.js|app\\.css|logo\\.svg)$ {{ auth_request off; add_header Cache-Control "no-cache"; }}
        location /fonts/ {{ auth_request off; expires 7d; add_header Cache-Control "public"; }}
        location /icons/ {{ expires 1h; add_header Cache-Control "public"; try_files $uri @repoicons; }}
        location @repoicons {{
            rewrite ^/icons/(.*)$ /papi/icons/$1 break;
            proxy_pass http://{api};
            proxy_set_header Cookie $http_cookie;
        }}
        location / {{
            error_page 401 = /login.html;
            try_files $uri $uri/ /index.html;
            add_header Cache-Control "no-cache";
        }}

{metrics_block}
{docs_block}
        location /papi/sd/ {{ return 404; }}
        location /papi/ {{
            auth_request off;
            proxy_pass http://{api};
            proxy_http_version 1.1;
            proxy_set_header Connection "";
            proxy_set_header Host $http_host;
            proxy_set_header X-Real-IP $remote_addr;
            proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
            proxy_set_header X-Forwarded-Proto $http_x_forwarded_proto;
            proxy_buffering off;
            proxy_cache off;
            proxy_read_timeout 1h;
            client_max_body_size 64k;
            add_header Cache-Control "no-store" always;
        }}
    }}

    # Internal listener: blackbox probe targets for the metrics backend (Prometheus http_sd format).
    # Do not expose this port outside the cluster / compose network.
    server {{
        listen {sd_port};
        server_name _;
        location = /sd/probes.json {{ proxy_pass http://{api}/papi/sd/probes; }}
        location = /healthz {{ default_type text/plain; return 200 "ok\\n"; }}
        location / {{ return 404; }}
    }}
}}
"""
os.makedirs("/tmp/nginx", exist_ok=True)
with open("/tmp/nginx/nginx.conf", "w") as f:
    f.write(re.sub(r"\n{3,}", "\n\n", conf))
print("nginx.conf rendered: metrics", metrics or "-", "| docs", docs or "-", "| frames", frames)
